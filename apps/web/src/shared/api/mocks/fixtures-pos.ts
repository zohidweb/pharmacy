export const DAY_MS = 86_400_000;

export const dateIn = (days: number) =>
  new Date(Date.now() + days * DAY_MS).toISOString().slice(0, 10);

export const minutesAgo = (minutes: number) =>
  new Date(Date.now() - minutes * 60_000).toISOString();

